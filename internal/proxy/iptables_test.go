func readTestdata(t *testing.T, name string) string {
	t.Helper()
	b, err := os.ReadFile("testdata/" + name)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestParseNATFindsProxyShRules(t *testing.T) {
	tb, err := ParseNAT(readTestdata(t, "iptables-save.txt"))
	if err != nil {
		t.Fatal(err)
	}
	var ovpn, wg, ssh int
	for _, f := range tb.Forwards {
		switch {
		case f.SSH:
			ssh++
		case f.Group == proxyapi.GroupOpenVPN:
			ovpn++
		case f.Group == proxyapi.GroupWireGuard:
			wg++
		}
		if f.ToIP != "198.51.100.20" {
			t.Errorf("адрес назначения %+v", f)
		}
	}
	if ovpn != 12 || wg != 6 || ssh != 2 {
		t.Fatalf("openvpn %d, wireguard %d, ssh %d", ovpn, wg, ssh)
	}
	// Порты из proxy.sh: 443 → 50443, 540 → 51443, 52080 → 51080.
	want := map[string]int{"tcp/443": 50443, "udp/443": 50443, "udp/540": 51443, "udp/52080": 51080, "udp/508": 50080}
	for _, f := range tb.Forwards {
		k := f.Proto + "/" + strconv.Itoa(f.Port)
		if p, ok := want[k]; ok && p != f.ToPort {
			t.Errorf("%s → %d, нужно %d", k, f.ToPort, p)
		}
		delete(want, k)
	}
	if len(want) != 0 {
		t.Errorf("не найдены правила %v", want)
	}
}

