// diffLines — номера строк (с единицы), в которых тексты различаются.
func diffLines(a, b string) []int {
	x, y := strings.Split(a, "\n"), strings.Split(b, "\n")
	var out []int
	for i := range x {
		if i >= len(y) || x[i] != y[i] {
			out = append(out, i+1)
		}
	}
	return out
}

func TestSetTargetChangesOnlyOwnGroup(t *testing.T) {
	orig := readTestdata(t, "iptables-save.txt")
	tb, _ := ParseNAT(orig)
	// Адрес общий у обеих групп: SNAT на старый остаётся, на новый добавляется.
	out, n, err := tb.SetTarget(proxyapi.GroupWireGuard, "198.51.100.99")
	if err != nil {
		t.Fatal(err)
	}
	if n != 7 { // шесть портов WG и SSH 21
		t.Fatalf("изменено %d, нужно 7", n)
	}
	nt, err := ParseNAT(out)
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range nt.Forwards {
		want := "198.51.100.20"
		if f.Group == proxyapi.GroupWireGuard {
			want = "198.51.100.99"
		}
		if f.ToIP != want {
			t.Errorf("%+v: адрес %s, нужен %s", f.Forward, f.ToIP, want)
		}
	}
	// Порты назначения не тронуты.
	for i, f := range tb.Forwards {
		if nt.Forwards[i].ToPort != f.ToPort || nt.Forwards[i].Port != f.Port || nt.Forwards[i].Proto != f.Proto {
			t.Errorf("правило %d изменилось не только адресом: %+v → %+v", i, f.Forward, nt.Forwards[i].Forward)
		}
	}
	// SNAT: старый на месте, новый добавлен сразу за ним.
	if !strings.Contains(out, "-A POSTROUTING -d 198.51.100.20/32 -j SNAT --to-source 203.0.113.10\n-A POSTROUTING -d 198.51.100.99/32 -j SNAT --to-source 203.0.113.10\nCOMMIT") {
		t.Errorf("SNAT:\n%s", out)
	}
	if !strings.HasSuffix(out, "\n") || !strings.HasPrefix(out, "# Generated by") {
		t.Errorf("края текста изменились")
	}
	// Строки OpenVPN, счётчики и комментарии — байт в байт.
	for _, l := range strings.Split(orig, "\n") {
		if strings.Contains(l, "--dport 443 ") || strings.HasPrefix(l, ":") || strings.HasPrefix(l, "#") {
			if !strings.Contains(out, l+"\n") {
				t.Errorf("строка потеряна: %q", l)
			}
		}
	}
}

func TestSetTargetBothGroupsMovesSNAT(t *testing.T) {
	tb, _ := ParseNAT(readTestdata(t, "iptables-save.txt"))
	mid, _, err := tb.SetTarget(proxyapi.GroupOpenVPN, "198.51.100.30")
	if err != nil {
		t.Fatal(err)
	}
	tb2, _ := ParseNAT(mid)
	out, _, err := tb2.SetTarget(proxyapi.GroupWireGuard, "198.51.100.30")
	if err != nil {
		t.Fatal(err)
	}
	// Старый адрес больше нигде не нужен: его SNAT заменён на новый, одним правилом.
	if strings.Contains(stripComments(out), "198.51.100.20") {
		t.Errorf("остался старый адрес:\n%s", out)
	}
	if strings.Count(out, "-j SNAT") != 1 || !strings.Contains(out, "-A POSTROUTING -d 198.51.100.30/32 -j SNAT --to-source 203.0.113.10\n") {
		t.Errorf("SNAT:\n%s", out)
	}
}

func TestSetTargetKeepsForeignRules(t *testing.T) {
	text := strings.Replace(readTestdata(t, "iptables-save.txt"), "COMMIT", `-A PREROUTING -p tcp -m tcp --dport 8443 -j DNAT --to-destination 198.51.100.20:8443
-A PREROUTING -i docker0 -p tcp -m tcp --dport 80 -j DNAT --to-destination 198.51.100.20:80
-A POSTROUTING -s 172.17.0.0/16 ! -o docker0 -j MASQUERADE
COMMIT`, 1)
	tb, _ := ParseNAT(text)
	out, n, err := tb.SetTarget(proxyapi.GroupOpenVPN, "198.51.100.40")
	if err != nil {
		t.Fatal(err)
	}
	if n != 13 { // 12 портов (tcp и udp) и SSH 20
		t.Fatalf("изменено %d", n)
	}
	for _, keep := range []string{
		"--dport 8443 -j DNAT --to-destination 198.51.100.20:8443\n",
		"-i docker0 -p tcp -m tcp --dport 80 -j DNAT --to-destination 198.51.100.20:80\n",
		"-A POSTROUTING -s 172.17.0.0/16 ! -o docker0 -j MASQUERADE\n",
	} {
		if !strings.Contains(out, keep) {
			t.Errorf("чужое правило тронуто: нет %q", keep)
		}
	}
}

